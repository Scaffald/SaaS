#!/usr/bin/env node
/**
 * Generates packages/supabase/functions/_shared/auth-email-templates.ts from
 * the branded auth templates (packages/supabase/email-templates/*.html) and
 * their subjects in packages/supabase/config.toml.
 *
 * Why a generated module: the `auth-email-hook` edge function renders these
 * same templates, and an edge function cannot read repo files at run time.
 * config.toml stays the source of truth (Supabase's own mailer reads it when
 * no hook is enabled); auth-email-templates.test.ts fails when this output is
 * stale, so the two cannot drift.
 *
 *   node scripts/generate-auth-email-templates.mjs          # write
 *   node scripts/generate-auth-email-templates.mjs --check  # exit 1 if stale
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SUPA = path.join(ROOT, 'packages/supabase')
const OUT = path.join(SUPA, 'functions/_shared/auth-email-templates.ts')
const KINDS = ['confirmation', 'invite', 'magic_link', 'recovery', 'email_change']

const toml = fs.readFileSync(path.join(SUPA, 'config.toml'), 'utf8')

function section(kind) {
  const start = toml.indexOf(`[auth.email.template.${kind}]`)
  if (start < 0) throw new Error(`config.toml has no [auth.email.template.${kind}]`)
  const rest = toml.slice(start)
  const end = rest.indexOf('\n[', 1)
  return end < 0 ? rest : rest.slice(0, end)
}

const templates = {}
for (const kind of KINDS) {
  const body = section(kind)
  const subject = /subject\s*=\s*"([^"]*)"/.exec(body)?.[1]
  const contentPath = /content_path\s*=\s*"([^"]*)"/.exec(body)?.[1]
  if (!subject || !contentPath) throw new Error(`[auth.email.template.${kind}] needs subject and content_path`)
  // content_path is relative to the directory that holds config.toml's
  // `supabase/` folder, i.e. packages/; "./supabase/x" means packages/supabase/x.
  const file = path.join(SUPA, '..', contentPath.replace(/^\.\//, ''))
  const resolved = fs.existsSync(file) ? file : path.join(SUPA, contentPath.replace(/^\.\/supabase\//, ''))
  templates[kind] = { subject, html: fs.readFileSync(resolved, 'utf8') }
}

const out = `// GENERATED by scripts/generate-auth-email-templates.mjs — do not edit.
// Source: packages/supabase/email-templates/*.html and the
// [auth.email.template.*] subjects in packages/supabase/config.toml.
// Regenerate after changing either; auth-email-templates.test.ts checks it.

export type AuthEmailKind = ${KINDS.map((k) => `'${k}'`).join(' | ')}

export const AUTH_EMAIL_TEMPLATES: Record<AuthEmailKind, { subject: string; html: string }> = ${JSON.stringify(templates, null, 2)}
`

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  if (current !== out) {
    console.error(`${path.relative(ROOT, OUT)} is stale. Run: node scripts/generate-auth-email-templates.mjs`)
    process.exit(1)
  }
  console.log('auth email templates up to date')
} else {
  fs.writeFileSync(OUT, out)
  console.log(`wrote ${path.relative(ROOT, OUT)}`)
}
